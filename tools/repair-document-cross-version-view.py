#!/usr/bin/env python3
"""repair-document-cross-version-view.py — restore fields un-projected by a bad declaration.

`reporting.cross_version_view.columns` is the DECLARATION the entity view
kb.doc_document is generated from. add-document-fields.py used to ASSIGN it
rather than merge, so each run silently un-projected every column it did not
relist. On canonical that removed `topics` from the view while leaving the data
untouched in doc_document__v2/__v3 — invisible to the Topic facet and to any SQL
over the view, with nothing erroring.

This repairs the declaration and nothing else: no data is read or written, no
fields are added. The view is regenerated by reporting-sync from the corrected
declaration, so the fix costs one template version and no migration.

Idempotent: if every expected column is already declared, the template is left
alone. The diff is verified to be declaration-only — any field-level change
aborts, because this script must never be the thing that alters a schema.

Env:
  KB_TARGET   base URL           (default https://localhost:8443 — the sandbox)
  KB_KEYFILE  admin API key file (default ~/.wip-deploy/default/secrets/api-key)
"""
import json
import os
import ssl
import sys
import urllib.request
from pathlib import Path

BASE = os.environ.get("KB_TARGET", "https://localhost:8443")
KEY = Path(os.environ.get("KB_KEYFILE",
    str(Path.home() / ".wip-deploy/default/secrets/api-key"))).expanduser().read_text().strip()
CTX = ssl._create_unverified_context()

# Every optional field added after v1 needs projecting, or it is invisible in the
# entity view. Only those actually declared on the template are included, so this
# is safe to run on an instance that has not had the later fields added yet.
EXPECT = ["topics", "content_hash", "repo_id", "path_tail"]
FIELD_KEYS = ["name", "label", "type", "mandatory", "default_value", "terminology_ref",
              "template_ref", "template_ref_version", "reference_type", "target_templates",
              "include_subtypes", "target_terminologies", "version_strategy", "file_config",
              "array_item_type", "array_terminology_ref", "array_template_ref",
              "array_template_ref_version", "array_file_config", "validation",
              "semantic_type", "full_text_indexed"]


def req(method, path, payload=None):
    r = urllib.request.Request(BASE + path,
        data=json.dumps(payload).encode() if payload is not None else None,
        headers={"X-API-Key": KEY, "Content-Type": "application/json"}, method=method)
    with urllib.request.urlopen(r, context=CTX, timeout=30) as resp:
        return json.load(resp)


print(f"target: {BASE}")
cur = req("GET", "/api/template-store/templates/by-value/DOCUMENT?namespace=kb")
on_template = {f["name"] for f in cur["fields"]}
rep = cur.get("reporting") or {}
cvv = rep.get("cross_version_view") or {}
have = dict(cvv.get("columns") or {})
want = [f for f in EXPECT if f in on_template]
missing = [f for f in want if f not in have]
print(f"  DOCUMENT v{cur['version']}  declared={sorted(have)}  should declare={sorted(want)}")
if not missing:
    print("SKIP: declaration already complete — nothing to repair")
    sys.exit(0)
print(f"  restoring: {missing}")

cols = dict(have)
for f in want:
    cols.setdefault(f, {})
rep["sync_enabled"] = True
rep["cross_version_view"] = {"versions": cvv.get("versions", "all"), "columns": cols}
resp = req("POST", "/api/template-store/templates", [{
    "value": cur["value"], "label": cur["label"], "namespace": "kb",
    "description": cur.get("description") or "",
    "identity_fields": cur.get("identity_fields") or [],
    "header_fields": cur.get("header_fields") or [],
    "fields": [{k: f[k] for k in FIELD_KEYS if f.get(k) is not None} for f in cur["fields"]],
    "rules": cur.get("rules") or [],
    "reporting": rep,
}])
item = resp["results"][0]
if item["status"] != "updated":
    sys.exit(f"ABORT: status={item['status']} error={item.get('error')}")
d = item.get("details") or {}
if any(d.get(k) for k in ("added_optional", "added_required", "removed",
                          "changed_type", "made_required", "modified_existing")):
    sys.exit(f"ABORT: expected a declaration-only change, got field diff {json.dumps(d)[:300]}")
print(f"OK: v{cur['version']} -> v{item.get('version')} (reporting declaration only, no field change)")
print("DONE")
